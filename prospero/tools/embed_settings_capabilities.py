#!/usr/bin/env python3
"""Generate the PS5 overlay's immutable metadata from the builder contract."""
import hashlib
import json
import pathlib
import sys

source, destination = map(pathlib.Path, sys.argv[1:])
raw = source.read_bytes()
data = json.loads(raw)
assert data['schemaVersion'] == 1 and data['titleId'] == 'PPSA74207'
keys = [s['key'] for s in data['settings']]
assert len(keys) == len(set(keys)) and not set(keys) & set(data['lockedSettings'])
assert data['lockedSettings']['prospero_profile_version'] == 34
# The shared 3.10.4 preset requests 60 FPS gameplay and 30 FPS menus.
# Both selectors must still restrict native rates to the supported 30/60 pair.
for rate_key, initial_rate in [('frame_rate', 60), ('menu_frame_rate', 30)]:
    setting = next(s for s in data['settings'] if s['key'] == rate_key)
    assert setting['default'] == initial_rate
    assert {choice['value'] for choice in setting['choices']} == {30, 60}

def quote(value):
    return json.dumps(str(value), ensure_ascii=False)

def raw_value(value):
    return value if isinstance(value, str) else json.dumps(value, allow_nan=False)

def kind(value):
    return ('kBoolean' if isinstance(value, bool) else 'kInteger' if isinstance(value, int)
            else 'kNumber' if isinstance(value, float) else 'kString')

lines = ['// Generated by embed_settings_capabilities.py. Do not edit.',
         '#pragma once', '#include <rex/ui/overlay/settings_prospero.h>',
         'namespace rex::ui::prospero_settings {',
         f'inline constexpr char kCapabilitiesSha256[] = "{hashlib.sha256(raw).hexdigest()}";',
         'inline constexpr GroupDefinition kGroups[] = {']
for group in data['groups']:
    lines.append('  {' + ', '.join(quote(group.get(k, group['label']))
                                  for k in ['id', 'label', 'labelIt']) + ', '
                 + quote(group.get('requiresFile', '')) + '},')
lines.append('};')
for i, setting in enumerate(data['settings']):
    choices = setting.get('choices', [])
    if choices:
        lines.append(f'inline constexpr ChoiceDefinition kChoices{i}[] = {{')
        for choice in choices:
            lines.append('  {' + ', '.join([quote(raw_value(choice['value'])), quote(choice['label']),
                quote(choice.get('labelIt', choice['label'])),
                'true' if choice.get('status') == 'experimental' else 'false']) + '},')
        lines.append('};')
lines.append('inline constexpr SettingDefinition kSettings[] = {')
for i, setting in enumerate(data['settings']):
    assert setting['applyMode'] in ['live', 'restart', 'fixed']
    assert setting['group'] in {g['id'] for g in data['groups']}
    if setting.get('requires'): assert setting['requires']['key'] in keys
    fields = [quote(setting['key']), quote(setting['label']), quote(setting.get('labelIt', setting['label'])),
              quote(setting['group']), quote(setting['description']),
              quote(setting.get('descriptionIt', setting['description'])), quote(raw_value(setting['default'])),
              'ValueKind::' + kind(setting['default']), 'Control::k' + setting['type'].title(),
              'Apply::k' + setting['applyMode'].title(),
              'true' if setting['status'] == 'experimental' else 'false',
              f'kChoices{i}' if setting.get('choices') else '{}',
              str(setting.get('min', 0)), str(setting.get('max', 0)), str(setting.get('step', 0)),
              quote(setting.get('requires', {}).get('key', '')),
              quote(raw_value(setting['requires']['value']) if setting.get('requires') else '')]
    lines.append('  {' + ', '.join(fields) + '},')
lines.append('};')
for i, preset in enumerate(data.get('presets', [])):
    assert set(preset['values']) <= set(keys)
    lines.append(f'inline constexpr PresetValue kPresetValues{i}[] = {{')
    for key, value in preset['values'].items():
        lines.append('  {' + quote(key) + ', ' + quote(raw_value(value)) + '},')
    lines.append('};')
lines.append('inline constexpr PresetDefinition kPresets[] = {')
for i, preset in enumerate(data.get('presets', [])):
    lines.append('  {' + ', '.join([quote(preset['id']), quote(preset['label']),
        quote(preset.get('labelIt', preset['label'])), quote(preset['group']), f'kPresetValues{i}']) + '},')
lines.extend(['};', '}  // namespace rex::ui::prospero_settings', ''])
output = '\n'.join(lines)
destination.parent.mkdir(parents=True, exist_ok=True)
if not destination.exists() or destination.read_text() != output:
    destination.write_text(output)
